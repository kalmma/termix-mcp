#!/usr/bin/env node
/**
 * Interactive setup: asks for your Termix base URL and API key, then
 * writes them to a local .env file so the MCP server can pick them up.
 *
 * Run with: npm run setup
 */
import { createInterface } from "node:readline/promises";
import { stdin, stdout } from "node:process";
import { writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const envPath = path.join(__dirname, "..", ".env");

function normalizeUrl(url) {
  return url.trim().replace(/\/+$/, "");
}

async function main() {
  console.log("Termix MCP server setup");
  console.log("------------------------");
  console.log(
    "This will ask for your Termix instance URL and an API key, and write\n" +
      "them to a local .env file (which is git-ignored, so it won't be\n" +
      "committed). You can also skip this and edit .env by hand.\n"
  );

  if (existsSync(envPath)) {
    console.log(`Note: ${envPath} already exists and will be overwritten.\n`);
  }

  console.log(
    "You'll be asked for your Termix API key after the URL - create one in\n" +
      "Termix under User Profile -> API Keys -> New Key if you haven't\n" +
      "already.\n" +
      "NOTE: some Termix versions only show a short prefix, e.g.\n" +
      "tmx_xxxxxxxx..., rather than the full secret value. If you can't find\n" +
      "the full value in your version's UI, check the Termix GitHub repo\n" +
      "(github.com/Termix-SSH/Termix) for current guidance, or use a JWT\n" +
      "bearer token instead - see the Termix API docs' Authentication\n" +
      "section. You can always update the key later by re-running\n" +
      "`npm run setup` or editing .env directly.\n"
  );

  const rl = createInterface({ input: stdin, output: stdout, terminal: false });

  let baseUrl = "";
  let apiKey = "";
  let stage = "url";

  stdout.write("Termix web UI URL (e.g. https://termix.example.com): ");

  // Using the async-iterator form (for await...of rl) rather than repeated
  // rl.question() calls - the latter can hang on piped/non-TTY stdin, while
  // iterating line-by-line works reliably for both interactive and piped use.
  for await (const rawLine of rl) {
    const line = rawLine.trim();

    if (stage === "url") {
      if (!line) {
        stdout.write("  Please enter a URL.\nTermix web UI URL: ");
        continue;
      }
      baseUrl = normalizeUrl(line);
      stage = "key";
      stdout.write("Termix API key: ");
      continue;
    }

    if (stage === "key") {
      if (!line) {
        stdout.write("  Please enter an API key.\nTermix API key: ");
        continue;
      }
      apiKey = line;
      break;
    }
  }

  rl.close();

  const contents =
    `# Generated by \`npm run setup\` on ${new Date().toISOString()}\n` +
    `TERMIX_BASE_URL=${baseUrl}\n` +
    `TERMIX_API_KEY=${apiKey}\n`;

  await writeFile(envPath, contents, { mode: 0o600 });

  console.log(`\nSaved to ${envPath}`);
  console.log(
    "\nNext steps:\n" +
      "  - Run the server directly with: npm start\n" +
      "  - Or point your MCP client (Claude Desktop / Claude Code) at\n" +
      "    src/index.js - it will load .env automatically, or you can set\n" +
      "    TERMIX_BASE_URL / TERMIX_API_KEY in the client's own config.\n" +
      "    See README.md for examples.\n"
  );
}

main().catch((err) => {
  console.error("\nSetup failed:", err.message);
  process.exit(1);
});
